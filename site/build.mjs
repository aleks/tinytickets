import { cp, mkdir, readFile, rm, writeFile, access, realpath } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join, basename } from 'node:path'
import { createPages, navigation, repository } from './content.mjs'

export const source = fileURLToPath(new URL('.', import.meta.url))
export const output = join(source, 'dist')
const screenshots = fileURLToPath(new URL('../screenshots/', import.meta.url))
const marker = '.tinytickets-docs-generated'
const escape = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c],
  )
const exists = async (path) => {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

export async function build() {
  if ((await exists(output)) && !(await exists(join(output, marker)))) {
    throw new Error(
      'site/dist exists without the generated-output marker. Move it before building.',
    )
  }
  const manifest = JSON.parse(await readFile(join(screenshots, 'manifest.json'), 'utf8'))
  const images = new Map()
  for (const item of manifest.screenshots) {
    if (basename(item.file) !== item.file || !item.file.endsWith('.png'))
      throw new Error('Invalid screenshot filename')
    const png = await readFile(join(screenshots, item.file))
    if (!png.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])))
      throw new Error(`Invalid PNG: ${item.file}`)
    images.set(item.file, { width: png.readUInt32BE(16), height: png.readUInt32BE(20) })
  }
  const figure = (file, alt, caption) => {
    const size = images.get(file)
    if (!size) throw new Error(`Unknown screenshot: ${file}`)
    return `<figure class="screenshot"><a href="assets/screenshots/${escape(file)}" aria-label="Open full image: ${escape(alt)}"><img src="assets/screenshots/${escape(file)}" width="${size.width}" height="${size.height}" alt="${escape(alt)}" loading="lazy" decoding="async"></a><figcaption>${escape(caption)} <a href="assets/screenshots/${escape(file)}">Open full image</a>.</figcaption></figure>`
  }
  const pages = createPages({
    figure,
    code: (text) => `<pre><code>${escape(text)}</code></pre>`,
    gallery: (items) =>
      `<div class="gallery">${items.map(([file, alt, caption]) => figure(file, alt, caption)).join('\n')}</div>`,
  })
  const bySlug = new Map(pages.map((page) => [page.slug, page]))
  const ordered = navigation.flatMap((group) => group.pages.map((slug) => bySlug.get(slug)))
  if (ordered.some((page) => !page) || new Set(ordered).size !== pages.length)
    throw new Error('Navigation and content differ')
  for (const page of pages) {
    if (!/^[a-z][a-z-]*$/.test(page.slug)) throw new Error(`Invalid page slug: ${page.slug}`)
    if (new Set(page.sections.map((section) => section.id)).size !== page.sections.length)
      throw new Error(`Duplicate section ID: ${page.slug}`)
  }
  // This directory is exclusively owned by the builder. Never clean an unknown output.
  await rm(output, { recursive: true, force: true })
  await mkdir(join(output, 'assets', 'screenshots'), { recursive: true })
  await writeFile(
    join(output, marker),
    'Generated by site/build.mjs. Do not edit this directory.\n',
  )
  await writeFile(join(output, '.nojekyll'), '')
  await cp(join(source, 'assets'), join(output, 'assets'), { recursive: true })
  for (const file of images.keys())
    await cp(join(screenshots, file), join(output, 'assets', 'screenshots', file))

  function nav(current, label) {
    return `<nav aria-label="${label}">${navigation.map((group) => `<div class="nav-group"><p class="nav-label">${escape(group.label)}</p><ul class="nav-list">${group.pages.map((slug) => `<li><a href="${slug}.html"${slug === current ? ' aria-current="page"' : ''}>${escape(bySlug.get(slug).title)}</a></li>`).join('')}</ul></div>`).join('')}</nav>`
  }
  const brand = `<a class="brand" href="index.html"><svg viewBox="0 0 32 32" fill="none" aria-hidden="true"><rect x="5" y="5" width="23" height="23" rx="5" fill="currentColor"/><path d="M10 11h13M10 16h9M10 21h6" stroke="var(--page)" stroke-width="1.7" stroke-linecap="round"/></svg>TinyTickets</a>`
  for (const [index, page] of ordered.entries()) {
    const previous = ordered[index - 1],
      next = ordered[index + 1]
    const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escape(page.description)}">
  <meta name="color-scheme" content="light dark">
  <title>${escape(page.title)} · TinyTickets documentation</title>
  <link rel="icon" href="assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="assets/style.css">
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>
  <aside class="sidebar" aria-label="Documentation sidebar">
    ${brand}<p class="brand-note">Documentation</p>
    ${nav(page.slug, 'Documentation')}
    <div class="rail-note"><p>Local application. Shared work records.</p><a href="${repository}">Source repository ↗</a></div>
  </aside>
  <div class="site-shell">
    <header class="topbar"><p>TinyTickets <span aria-hidden="true">/</span> Documentation</p><a href="${repository}">Source ↗</a></header>
    <details class="mobile-nav"><summary>Browse documentation</summary>${nav(page.slug, 'Mobile documentation')}</details>
    <div class="page-layout">
      <main id="main" tabindex="-1">
        <header><p class="eyebrow">${escape(page.group)}</p><h1>${escape(page.title)}</h1><p class="lead">${escape(page.lead)}</p></header>
        ${page.sections.map((section) => `<section aria-labelledby="${section.id}"><h2 id="${section.id}">${escape(section.title)}</h2>${section.html}</section>`).join('\n')}
        <nav class="page-footer" aria-label="Page sequence">${previous ? `<a href="${previous.slug}.html"><small>Previous</small>← ${escape(previous.title)}</a>` : ''}${next ? `<a class="next" href="${next.slug}.html"><small>Next</small>${escape(next.title)} →</a>` : ''}</nav>
        <footer class="site-footer"><p>Static documentation. This site does not read or change application data.</p><p>Written in short, controlled English. Formal ASD-STE100 compliance is not certified. <a href="${repository}/issues">Report a documentation problem</a>.</p></footer>
      </main>
      <nav class="toc" aria-label="On this page"><p>On this page</p><ul>${page.sections.map((section) => `<li><a href="#${section.id}">${escape(section.title)}</a></li>`).join('')}</ul></nav>
    </div>
  </div>
</body>
</html>\n`
    await writeFile(join(output, `${page.slug}.html`), html)
  }
  await writeFile(
    join(output, 'build.json'),
    JSON.stringify(
      {
        pages: ordered.map(({ slug, title }) => ({ file: `${slug}.html`, title })),
        screenshots: [...images.keys()],
      },
      null,
      2,
    ) + '\n',
  )
  console.log(
    `Built ${pages.length} documentation pages and ${images.size} screenshots in site/dist`,
  )
  return output
}

const entry = process.argv[1] ? await realpath(process.argv[1]).catch(() => null) : null
if (entry === (await realpath(fileURLToPath(import.meta.url)))) await build()
